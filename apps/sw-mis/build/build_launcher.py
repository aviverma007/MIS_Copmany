"""
Builder: assembles backend/*.py + frontend/ into the single shippable
sw_mis_app.py (embeds everything as base64 inside one .py file).

Usage:
    cd build
    python build_launcher.py
    # -> writes ../dist/sw_mis_app.py

This script itself is a *development* tool - it is not needed to run the
application day-to-day (that's sw_mis_app.py, or backend/dev_server.py
for live-editing). It only needs to be re-run after changing backend/ or
frontend/ source, to refresh the shipped single-file build.
"""
import base64
import io
import textwrap
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
BACKEND = PROJECT_ROOT / "backend"
FRONTEND = PROJECT_ROOT / "frontend"
OUT = PROJECT_ROOT / "dist" / "sw_mis_app.py"

MODULES = ["engine", "analytics", "export_excel", "export_pdf", "api_app"]

module_b64 = {}
for name in MODULES:
    src = (BACKEND / f"{name}.py").read_text(encoding="utf-8")
    module_b64[name] = base64.b64encode(src.encode("utf-8")).decode("ascii")

# Zip the frontend folder (index.html + static/...) in memory, contents at
# the zip root (no wrapper folder) so the launcher can extract it as-is.
zip_buf = io.BytesIO()
with zipfile.ZipFile(zip_buf, "w", zipfile.ZIP_DEFLATED) as zf:
    for path in sorted(FRONTEND.rglob("*")):
        if path.is_file():
            zf.write(path, path.relative_to(FRONTEND))
frontend_b64 = base64.b64encode(zip_buf.getvalue()).decode("ascii")


def chunk(s, width=100):
    """Wrap a long base64 string across multiple short string literals so no
    single line becomes absurdly long in the source file."""
    lines = textwrap.wrap(s, width)
    return "\n".join(f'    "{line}"' for line in lines)


parts = []

parts.append('''#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
================================================================================
 Smartworld Customer Complaint MIS  -  single-file local application launcher
================================================================================

WHAT THIS IS
    A self-contained Customer Complaint Management MIS / Dashboard for
    Smartworld. Upload the "Compile SW Data" workbook, and it builds a full
    executive dashboard: KPIs, RAG indicators, multi-select cross-filtering,
    project / area / SLA / owner analysis, daily-trend, a searchable case
    table with drill-down, data-quality checks, management-attention
    exceptions, and Excel / PDF exports - all computed dynamically from the
    workbook, nothing is hard-coded.

    This file is generated by build/build_launcher.py from the source
    project (backend/ + frontend/). Edit the source, not this file.

HOW TO RUN
    1. Install Python 3.9+ (Windows: https://python.org - tick "Add to PATH").
    2. Double-click this file, OR from a command prompt:
           python sw_mis_app.py
    3. First run installs a handful of Python packages automatically
       (needs internet once). A browser tab opens automatically at
       http://127.0.0.1:8000 once the server is ready.
    4. Upload your Smartworld workbook (.xlsx) in the browser and explore.
    5. Press Ctrl+C in this window to stop the app.

WHAT IT NEEDS
    - Python 3.9+ and pip (for the one-time package install).
    - No database, no Docker, no Node.js/npm, no internet after the first run.
    - Everything - backend AND frontend - lives inside this one .py file.
      Running it creates a small "sw_mis_appdata" folder next to this
      script to unpack the (embedded) web UI into; your uploaded data is
      only ever held in memory for the current session, never written to
      disk, and never leaves this machine.

================================================================================
"""
import sys
import os
import io
import time
import socket
import zipfile
import base64
import shutil
import threading
import subprocess
import webbrowser
from pathlib import Path

APP_TITLE = "Smartworld Customer Complaint MIS"
PREFERRED_PORT = 8000
PORT_FALLBACKS = list(range(8000, 8011))

# -----------------------------------------------------------------------------
# STEP 1 - required package check / auto-install (stdlib only up to here)
# -----------------------------------------------------------------------------
# (import name, pip package name, minimum purpose)
REQUIRED_PACKAGES = [
    ("pandas", "pandas"),
    ("numpy", "numpy"),
    ("openpyxl", "openpyxl"),
    ("fastapi", "fastapi"),
    ("uvicorn", "uvicorn"),
    ("multipart", "python-multipart"),
    ("reportlab", "reportlab"),
    ("matplotlib", "matplotlib"),
    ("PIL", "Pillow"),
]


def _banner():
    line = "=" * 78
    print(line)
    print(f"  {APP_TITLE}")
    print(line)


def ensure_packages():
    missing = []
    for import_name, pip_name in REQUIRED_PACKAGES:
        try:
            __import__(import_name)
        except ImportError:
            missing.append(pip_name)
    if not missing:
        print("[1/4] Required packages already installed.")
        return
    print(f"[1/4] Installing {len(missing)} missing package(s): {', '.join(missing)}")
    print("       (one-time setup, needs internet - this can take a minute)")
    try:
        subprocess.check_call([sys.executable, "-m", "pip", "install", "--quiet", "--disable-pip-version-check", *missing])
    except subprocess.CalledProcessError:
        # retry with --user in case of a permissions issue on a locked-down machine
        try:
            subprocess.check_call([sys.executable, "-m", "pip", "install", "--quiet", "--user", "--disable-pip-version-check", *missing])
        except subprocess.CalledProcessError:
            print("\\n  Could not automatically install required packages.")
            print(f"  Please run this manually, then re-run the app:\\n")
            print(f"      {sys.executable} -m pip install {' '.join(missing)}\\n")
            sys.exit(1)
    # verify
    still_missing = []
    for import_name, pip_name in REQUIRED_PACKAGES:
        try:
            __import__(import_name)
        except ImportError:
            still_missing.append(pip_name)
    if still_missing:
        print(f"  Still missing after install attempt: {', '.join(still_missing)}")
        sys.exit(1)
    print("       All required packages are ready.")


# -----------------------------------------------------------------------------
# STEP 2 - embedded application source (backend modules) and web UI (frontend)
# -----------------------------------------------------------------------------
''')

for name in MODULES:
    parts.append(f'_SRC_{name.upper()}_B64 = (\n{chunk(module_b64[name])}\n)\n')

parts.append(f'\n_FRONTEND_ZIP_B64 = (\n{chunk(frontend_b64)}\n)\n')

parts.append('''

def _load_embedded_module(name, b64_source):
    """Materialize one of the embedded backend modules as a real importable
    module (registered in sys.modules) so the modules' own `import engine`,
    `import analytics` etc. statements resolve correctly against each other,
    exactly as if they were separate files on disk."""
    import types
    source = base64.b64decode(b64_source).decode("utf-8")
    mod = types.ModuleType(name)
    sys.modules[name] = mod
    exec(compile(source, f"<embedded:{name}.py>", "exec"), mod.__dict__)
    return mod


def _extract_frontend(target_dir: Path):
    """Unpack the embedded web UI (React + Chart.js, self-hosted, no CDN
    dependency) into a local folder so FastAPI can serve it as static files."""
    if target_dir.exists():
        shutil.rmtree(target_dir, ignore_errors=True)
    target_dir.mkdir(parents=True, exist_ok=True)
    zip_bytes = base64.b64decode(_FRONTEND_ZIP_B64)
    with zipfile.ZipFile(io.BytesIO(zip_bytes)) as zf:
        zf.extractall(target_dir)
    return target_dir


def _find_open_port(candidates):
    for port in candidates:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.settimeout(0.3)
            try:
                s.bind(("127.0.0.1", port))
                return port
            except OSError:
                continue
    return None


def _wait_and_open_browser(port):
    import urllib.request
    url = f"http://127.0.0.1:{port}/"
    for _ in range(100):  # up to ~20s
        try:
            urllib.request.urlopen(f"http://127.0.0.1:{port}/api/status", timeout=1)
            break
        except Exception:
            time.sleep(0.2)
    try:
        webbrowser.open(url)
    except Exception:
        pass
    print(f"\\n  Dashboard ready -> {url}")
    print("  (If the browser didn't open automatically, copy that URL into one.)\\n")


def main():
    _banner()
    ensure_packages()

    print("[2/4] Loading application modules...")
    engine = _load_embedded_module("engine", _SRC_ENGINE_B64)
    analytics = _load_embedded_module("analytics", _SRC_ANALYTICS_B64)
    export_excel = _load_embedded_module("export_excel", _SRC_EXPORT_EXCEL_B64)
    export_pdf = _load_embedded_module("export_pdf", _SRC_EXPORT_PDF_B64)
    api_app = _load_embedded_module("api_app", _SRC_API_APP_B64)

    script_dir = Path(__file__).resolve().parent
    app_dir = script_dir / "sw_mis_appdata"
    app_dir.mkdir(exist_ok=True)

    print("[3/4] Preparing local web interface...")
    webapp_dir = _extract_frontend(app_dir / "static_frontend")
    api_app.mount_frontend(str(webapp_dir))

    port = _find_open_port(PORT_FALLBACKS)
    if port is None:
        print("  Could not find a free port between 8000-8010.")
        print("  Close other local servers and try again.")
        sys.exit(1)

    print(f"[4/4] Starting local server on port {port}...")
    threading.Thread(target=_wait_and_open_browser, args=(port,), daemon=True).start()

    import uvicorn
    try:
        uvicorn.run(api_app.app, host="127.0.0.1", port=port, log_level="warning")
    except KeyboardInterrupt:
        pass
    finally:
        print("\\n  Smartworld Customer Complaint MIS stopped. Your data was only ever kept in memory")
        print("  for this session and has not been written anywhere.")


if __name__ == "__main__":
    main()
''')

OUT.parent.mkdir(exist_ok=True)
OUT.write_text("".join(parts), encoding="utf-8")
print(f"Wrote {OUT} ({OUT.stat().st_size / 1024:.1f} KB)")
